//! Allocation-free bounded UTF-8 values and the QSL-LZ v1 string frame.
//!
//! Bounds refer to UTF-8 **bytes**. This format is intentionally not LZ4:
//! literal runs and matches use explicit controls and schema-sized offsets.
//! A raw fallback guarantees `frame_size <= HEADER_BYTES + original_length`.
//! Inline/LZ storage comes from the containing value or caller output. CopyGuard
//! owns a reusable SerOut allocation; decoding into prepared storage does not allocate.

use std::{fmt, mem::MaybeUninit, ptr, slice, str};

/// Strings shorter than this are copied raw, without a compression probe.
pub const STRING_COMPRESSION_MIN_BYTES: usize = 32;
/// Encoder policy revision; frames remain readable by the QSL-LZ v1 decoder.
/// Pin this along with the schema when comparing bytes across encoder versions.
pub const STRING_ENCODER_REVISION: u8 = 2;
const MIN_MATCH: usize = 4;
const MAX_MATCH: usize = 131;

mod header_sealed {
    pub trait Sealed {}
    impl Sealed for u8 {}
    impl Sealed for u16 {}
    impl Sealed for u32 {}
}

/// Native QSL-LZ length/mode word selected by schema analysis.
/// Only u8, u16 and u32 implement this sealed trait.
pub trait StringHeader: header_sealed::Sealed {
    const BYTES: usize;
    const MODE: u32;
    /// # Safety
    /// BYTES readable bytes remain at input.
    unsafe fn load(input: *const u8) -> u32;
    /// # Safety
    /// BYTES exclusive writable bytes remain at output; value fits this word.
    unsafe fn store(output: *mut u8, value: u32);
}
macro_rules! string_header {
    ($word:ty) => {
        impl StringHeader for $word {
            const BYTES: usize = std::mem::size_of::<Self>();
            const MODE: u32 = 1 << (<$word>::BITS - 1);
            #[inline(always)]
            unsafe fn load(input: *const u8) -> u32 {
                Self::from_le(ptr::read_unaligned(input.cast::<Self>())) as u32
            }
            #[inline(always)]
            unsafe fn store(output: *mut u8, value: u32) {
                ptr::write_unaligned(output.cast::<Self>(), (value as Self).to_le());
            }
        }
    };
}
string_header!(u8);
string_header!(u16);
string_header!(u32);

/// An owned UTF-8 value whose storage is part of the containing Rust object.
///
/// Generated by `string(MIN..MAX) field |decompress=true|`. No heap allocation
/// occurs during construction, encoding or decoding. `MAX` must fit `u16`.
/// The QSL field's minimum remains a caller precondition of unchecked encoding.
#[repr(C)]
pub struct InlineString<const MAX: usize> {
    len: u32,
    bytes: [MaybeUninit<u8>; MAX],
}

impl<const MAX: usize> InlineString<MAX> {
    /// Maximum decoded UTF-8 byte count, fixed by the schema.
    pub const MAX_BYTES: usize = MAX;
    /// Length and mode share a word: 1 byte through MAX=127, then 2 or 4.
    pub const HEADER_BYTES: usize = if MAX <= 127 {
        1
    } else if MAX <= 32767 {
        2
    } else {
        4
    };
    /// Width of each backward distance; match lengths use the control byte.
    pub const OFFSET_BYTES: usize = if MAX <= 255 { 1 } else { 2 };

    /// Construct an empty value without initializing unused capacity.
    /// Dependencies: `MaybeUninit`; no allocator or runtime loop.
    #[inline(always)]
    pub const fn new() -> Self {
        assert!(MAX <= u16::MAX as usize);
        Self {
            bytes: [MaybeUninit::uninit(); MAX],
            len: 0,
        }
    }

    /// Copy valid UTF-8 into the statically bounded storage.
    /// # Safety
    /// `value.len() <= MAX`; the containing QSL field's minimum must also hold.
    #[inline(always)]
    pub unsafe fn from_str_unchecked(value: &str) -> Self {
        let mut result = Self::new();
        ptr::copy_nonoverlapping(
            value.as_ptr(),
            result.bytes.as_mut_ptr().cast(),
            value.len(),
        );
        result.len = value.len() as u32;
        result
    }

    /// Construct LEN ASCII spaces without a heap allocation.
    /// Used by generated defaults with a positive minimum byte length.
    #[inline]
    pub const fn spaces<const LEN: usize>() -> Self {
        assert!(LEN <= MAX);
        let mut value = Self::new();
        let mut index = 0;
        while index < LEN {
            value.bytes[index] = MaybeUninit::new(b' ');
            index += 1;
        }
        value.len = LEN as u32;
        value
    }

    /// Current UTF-8 byte count, without inspecting the payload.
    #[inline(always)]
    pub fn len(&self) -> usize {
        self.len as usize
    }

    /// Whether the value has zero bytes.
    #[inline(always)]
    pub fn is_empty(&self) -> bool {
        self.len == 0
    }

    /// Borrow only initialized, valid UTF-8 bytes; unused capacity is hidden.
    #[inline(always)]
    pub fn as_str(&self) -> &str {
        unsafe {
            str::from_utf8_unchecked(slice::from_raw_parts(
                self.bytes.as_ptr().cast(),
                self.len(),
            ))
        }
    }

    /// Worst-case frame size. Exact compressed size depends on runtime content.
    /// This bound is sufficient for encoding directly into the final buffer.
    #[inline(always)]
    pub fn wire_capacity(&self) -> usize {
        Self::HEADER_BYTES + self.len()
    }

    /// Encode once into a preallocated final frame, returning bytes initialized.
    /// # Safety
    /// `output` must be exclusive, nonoverlapping and writable for
    /// `self.wire_capacity()` bytes. Values must obey their QSL field bounds.
    #[inline(always)]
    pub unsafe fn encode_to(&self, output: *mut u8) -> usize {
        encode_bounded::<MAX>(self.bytes.as_ptr().cast(), self.len(), output)
    }

    /// Encode with the native header word selected during schema analysis.
    /// # Safety
    /// Same storage contract as encode_to. H must match this MAX's header width.
    #[inline(always)]
    pub unsafe fn encode_to_with<H: StringHeader>(&self, output: *mut u8) -> usize {
        encode_bounded_with::<MAX, H>(self.bytes.as_ptr().cast(), self.len(), output)
    }

    /// Encode the same frame in raw mode, for an equivalent no-compression path.
    /// # Safety
    /// Same capacity, exclusivity and nonoverlap contract as `encode_to`.
    #[inline(always)]
    pub unsafe fn encode_raw_to(&self, output: *mut u8) -> usize {
        write_header::<MAX>(output, self.len(), false);
        copy_payload::<MAX>(
            self.bytes.as_ptr().cast(),
            output.add(Self::HEADER_BYTES),
            self.len(),
        );
        self.wire_capacity()
    }

    /// Decode directly into caller-owned uninitialized storage, without moving MAX bytes.
    /// # Safety
    /// input is a complete valid UTF-8 frame; output is aligned and writable for Self,
    /// uninitialized (or its previous value has been dropped), and does not overlap input.
    #[inline(always)]
    pub unsafe fn decode_into(input: *const u8, output: *mut Self) -> usize {
        let (len, used) = decode_bounded::<MAX>(input, ptr::addr_of_mut!((*output).bytes).cast());
        ptr::addr_of_mut!((*output).len).write(len as u32);
        used
    }

    /// Decode with an analysis-selected native header word into final storage.
    /// # Safety
    /// Same contract as decode_into; H must match this MAX's header width.
    #[inline(always)]
    pub unsafe fn decode_into_with<H: StringHeader>(input: *const u8, output: *mut Self) -> usize {
        let (len, used) =
            decode_bounded_with::<MAX, H>(input, ptr::addr_of_mut!((*output).bytes).cast());
        ptr::addr_of_mut!((*output).len).write(len as u32);
        used
    }

    /// Decode a raw-only frame using the analysis-selected header word.
    /// # Safety
    /// Same contract as decode_raw_into; H must match this MAX's header width.
    #[inline(always)]
    pub unsafe fn decode_raw_into_with<H: StringHeader>(
        input: *const u8,
        output: *mut Self,
    ) -> usize {
        assert!(H::BYTES == Self::HEADER_BYTES);
        let word = H::load(input);
        std::hint::assert_unchecked(word & H::MODE == 0 && word as usize <= MAX);
        let len = word as usize;
        ptr::copy_nonoverlapping(
            input.add(H::BYTES),
            ptr::addr_of_mut!((*output).bytes).cast(),
            len,
        );
        ptr::addr_of_mut!((*output).len).write(len as u32);
        H::BYTES + len
    }

    /// Return a value decoded with the analysis-selected header word.
    /// # Safety
    /// Same contract as decode_from; H must match this MAX's header width.
    #[inline(always)]
    pub unsafe fn decode_from_with<H: StringHeader>(input: *const u8) -> (Self, usize) {
        let mut result = MaybeUninit::<Self>::uninit();
        let used = Self::decode_into_with::<H>(input, result.as_mut_ptr());
        (result.assume_init(), used)
    }

    /// Return a raw-only value without inspecting a runtime compression mode.
    /// # Safety
    /// Same contract as decode_raw_into; H must match this MAX's header width.
    #[inline(always)]
    pub unsafe fn decode_raw_from_with<H: StringHeader>(input: *const u8) -> (Self, usize) {
        let mut result = MaybeUninit::<Self>::uninit();
        let used = Self::decode_raw_into_with::<H>(input, result.as_mut_ptr());
        (result.assume_init(), used)
    }

    /// Decode a raw-only bounded frame into final storage.
    /// # Safety
    /// Same storage contract as decode_into; the frame must have its mode bit clear.
    #[inline(always)]
    pub unsafe fn decode_raw_into(input: *const u8, output: *mut Self) -> usize {
        let (len, compressed) = read_header::<MAX>(input);
        std::hint::assert_unchecked(!compressed && len <= MAX);
        ptr::copy_nonoverlapping(
            input.add(Self::HEADER_BYTES),
            ptr::addr_of_mut!((*output).bytes).cast(),
            len,
        );
        ptr::addr_of_mut!((*output).len).write(len as u32);
        Self::HEADER_BYTES + len
    }

    /// Decode eagerly into inline storage, returning the value and frame length.
    /// # Safety
    /// `input` must contain a complete canonical frame for this `MAX`, whose
    /// decoded bytes are valid UTF-8 and satisfy the containing field's range.
    #[inline(always)]
    pub unsafe fn decode_from(input: *const u8) -> (Self, usize) {
        let mut result = MaybeUninit::<Self>::uninit();
        let consumed = Self::decode_into(input, result.as_mut_ptr());
        (result.assume_init(), consumed)
    }
}

impl<const MAX: usize> Default for InlineString<MAX> {
    #[inline(always)]
    fn default() -> Self {
        Self::new()
    }
}
impl<const MAX: usize> Clone for InlineString<MAX> {
    fn clone(&self) -> Self {
        unsafe { Self::from_str_unchecked(self.as_str()) }
    }
}
